export function localGlyph(name: string, criterion: string, taken: string[] = []): string | null {
  const text = `${name} ${criterion}`
  for (const [rx, cands] of RULES) {
    if (!rx.test(text)) continue
    const free = cands.find((c) => GLYPHS[c] && !taken.includes(c))
    if (free) return free
  }
  return null
}
